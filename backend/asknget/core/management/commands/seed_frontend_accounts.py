"""Three test accounts for the frontend developer, with random passwords written to a git-ignored env file, never printed.

    python manage.py seed_frontend_accounts --yes-this-is-staging --env-file <frontend folder>/.env.local

Run it against the STAGING database only (the flag is a reminder: it creates staff and seller logins). It creates or updates:

    fe-customer@asknget.test   a buyer
    fe-seller@asknget.test     a seller: a member of the demo store (Huda Beauty) with `manage` on every section, so the whole seller portal
                               works with real data; team management and plan changes stay owner-only, as for any member
    fe-admin@asknget.test      staff (is_staff, not a superuser) with the Administrator role: every /admin/* endpoint

and writes E2E_CUSTOMER_EMAIL / E2E_CUSTOMER_PASSWORD, E2E_SELLER_*, E2E_ADMIN_* into the env file (other lines are kept). Running it again gives every account a NEW password and
rewrites the file, which is also how to rotate them. The passwords exist nowhere else: not in the output, the database (only the hash), or the repository.
"""

import secrets
from pathlib import Path

from django.core.management.base import BaseCommand, CommandError
from django.utils import timezone

from accounts.models import User
from sellers.models import Store
from team.models import StoreMember, TeamRole
from team.sections import SECTIONS

ACCOUNTS = (
    ("CUSTOMER", "fe-customer@asknget.test", "Frontend Test Customer", {}),
    ("SELLER", "fe-seller@asknget.test", "Frontend Test Seller", {"is_seller": True}),
    ("ADMIN", "fe-admin@asknget.test", "Frontend Test Admin", {"is_staff": True}),
)
HEADER = "# Test accounts on the backend Preview (staging), generated by the backend session. Never commit this file or print these values."


def merge_env(path: Path, values: dict) -> None:
    # utf-8-sig and the replace: Windows PowerShell writes a byte-order mark that would glue itself to the first variable's name
    lines = [line.replace("﻿", "") for line in path.read_text(encoding="utf-8-sig").splitlines()] if path.exists() else []
    keep = [line for line in lines if line.split("=", 1)[0].strip() not in values]
    if HEADER not in keep:
        keep = [HEADER] + keep
    keep += [f"{key}={value}" for key, value in values.items()]
    path.write_text("\n".join(keep) + "\n", encoding="utf-8")


class Command(BaseCommand):
    help = "Create test logins (customer, seller, staff) for the frontend developer; passwords go to an env file, never to the output (staging only)."

    def add_arguments(self, parser):
        parser.add_argument("--env-file", required=True, help="Where to write the E2E_* variables, e.g. <frontend>/.env.local (must be git-ignored)")
        parser.add_argument("--yes-this-is-staging", action="store_true", help="Required: this creates staff and seller logins, so never run it on production")
        parser.add_argument("--store-slug", default="huda-beauty", help="The demo store the test seller joins")

    def handle(self, *args, env_file, store_slug, **options):
        if not options["yes_this_is_staging"]:
            raise CommandError("Refusing: this creates a staff login and a seller login. Pass --yes-this-is-staging, and only against the staging database.")
        store = Store.objects.filter(slug=store_slug).first()
        if store is None:
            raise CommandError(f"No store with slug {store_slug!r} here: run seed_demo first (staging only).")
        role = TeamRole.objects.filter(key="manager").first()
        now = timezone.now()
        values = {}
        for prefix, email, name, flags in ACCOUNTS:
            password = secrets.token_urlsafe(18)
            user, _ = User.objects.get_or_create(email=email, defaults={"full_name": name, **flags})
            for field, value in flags.items():
                setattr(user, field, value)
            user.is_superuser = False
            user.is_active = True
            user.set_password(password)
            user.email_verified_at = user.email_verified_at or now
            user.save()
            if prefix == "SELLER":
                member, _ = StoreMember.objects.get_or_create(store=store, email=email, defaults=dict(user=user, role=role, status="active", joined_at=now, invited_by=store.owner))
                member.user, member.role, member.status = user, role, "active"
                member.permissions = {section: "manage" for section in SECTIONS}
                member.joined_at = member.joined_at or now
                member.save()
            if prefix == "ADMIN":                                 # every staff permission, every market
                from django.contrib.auth.models import Group

                user.groups.add(Group.objects.get(name="Administrator"))
            values[f"E2E_{prefix}_EMAIL"] = email
            values[f"E2E_{prefix}_PASSWORD"] = password
        merge_env(Path(env_file), values)
        self.stdout.write(f"Wrote {len(values)} variables for {len(ACCOUNTS)} accounts to {env_file} (passwords are not shown).")
        for _prefix, email, _name, _flags in ACCOUNTS:
            self.stdout.write(f"  {email}")
